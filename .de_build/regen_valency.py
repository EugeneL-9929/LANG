def trans_label(p):
    p2 = re.sub(r"sich \+ [AD]", "", p)
    p2 = re.sub(r"\+\s*R\b", "", p2)
    for m in re.finditer(r"(?:(?:jn|jm)\.\s*/\s*etw\.|jn\.|jm\.|etw\.)\s*\(([ADG])\)", p2):
        pre = re.findall(r"[A-Za-zÄÖÜäöüß]+", p2[:m.start()])
        if m.group(1) == "A" and not (pre and pre[-1].lower() in PREPS):
            return "vt"
    flat = p2.replace("+", " ")
    for m in re.finditer(r"(?<![A-Za-zÄÖÜäöüß])A(?![A-Za-zÄÖÜäöüß])", flat):
        pre = re.findall(r"[A-Za-zÄÖÜäöüß]+", flat[:m.start()])
        if not (pre and pre[-1].lower() in PREPS):
            return "vt"
    return "vi"

