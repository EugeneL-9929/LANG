def main():
    with open(VOCAB, encoding="utf-8-sig") as f:
        rd = csv.DictReader(f)
        fields = rd.fieldnames
        rows = list(rd)
    for r in rows:
        if r["词性"] not in ("vt", "vi", "v"):
            continue
        lemma = r["词条"]
        if lemma in VAL:
            r["配价搭配"] = VAL[lemma]
        elif r["词性"] in ("vt", "v"):
            r["配价搭配"] = "+ A"
        else:
            r["配价搭配"] = ""
        # 让词性与新配价一致
        r["词性"] = "v" if lemma in V_SET else trans_label(r["配价搭配"])
        if "sich + " in r["配价搭配"] and r["反身用法"] == "非反身":
            note = SICH_NOTE.get(lemma, "sich " + lemma)
            r["反身用法"] = "可反身：" + note
        if (r["反身用法"].startswith("反身（必须带反身代词）")
                and not lemma.startswith("sich ")):
            r["反身用法"] = "非反身"

    def write(path, data):
        with open(path, "w", encoding="utf-8-sig", newline="") as f:
            w = csv.DictWriter(f, fieldnames=fields)
            w.writeheader()
            w.writerows(data)

    write(VOCAB, rows)
    for lv in ["A1", "A2", "B1", "B2", "C1", "C2"]:
        write(os.path.join(ROOT, lv + "_vocabulary.csv"),
              [r for r in rows if r["级别"] == lv])
    n = sum(1 for r in rows if r["配价搭配"].strip())
    print("重建完成，非空配价行:", n)


if __name__ == "__main__":
    main()
